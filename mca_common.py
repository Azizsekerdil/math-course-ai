def strip_rtf(text):
    """Small RTF-to-text fallback good enough for READ ME files."""
    if not text:
        return ""
    # decode common escaped hex chars
    def repl_hex(m):
        try:
            return bytes.fromhex(m.group(1)).decode("cp1252", errors="ignore")
        except Exception:
            return ""
    text = re.sub(r"\\'([0-9a-fA-F]{2})", repl_hex, text)
    text = re.sub(r"\\par[d]?", "\n", text)
    text = re.sub(r"\\tab", "\t", text)
    text = re.sub(r"\{\\\*[^{}]*\}", "", text)
    text = re.sub(r"\\[a-zA-Z]+-?\d* ?", "", text)
    text = text.replace("{", "").replace("}", "")
    text = text.replace("\\", "")
    text = re.sub(r"\n\s*\n\s*\n+", "\n\n", text)
    return text.strip()


def read_text_file(path, max_chars=250_000):
    path = Path(path)
    ext = path.suffix.lower()
    try:
        if ext == ".rtf":
            raw = path.read_text(encoding="utf-8", errors="ignore")
            return strip_rtf(raw)[:max_chars]
        if ext in {".txt", ".md"}:
            return path.read_text(encoding="utf-8", errors="ignore")[:max_chars]
        if ext == ".docx" and _lazy_docx():
            document = _lazy_docx().Document(str(path))
            text = "\n".join(p.text for p in document.paragraphs)
            return text[:max_chars]
        if ext == ".pdf" and fitz:
            out = []
            with fitz.open(str(path)) as doc:
                for i, page in enumerate(doc):
                    if i >= 30:
                        out.append("\n[Text extraction stopped after 30 pages for safety.]\n")
                        break
                    out.append(f"\n--- Page {i+1} ---\n" + page.get_text("text"))
            return "\n".join(out)[:max_chars]
    except Exception as exc:
        return f"Could not read file: {exc}"
    return "This file type can be opened externally, but text extraction is not available."


