def normalize_lang(lang):
    """'English', 'en-US', 'EN' → 'en'; geri kalan her şey → 'tr'."""
    return "en" if str(lang or "").strip().lower().startswith("en") else "tr"


def t2(tr, en, lang="tr"):
    """İki dilli metin seçici. Boş İngilizce verilirse Türkçesine düşer."""
    if normalize_lang(lang) == "en":
        return en if (en is not None and str(en) != "") else tr
    return tr


def app_lang(app, default="tr"):
    """Bir panelin sahibi uygulamadan dilini güvenle okur.

    Panel testlerde sahte bir `app` ile de kurulabildiği için hata yutulur.
    """
    try:
        return normalize_lang(getattr(app, "language", default))
    except Exception:
        return normalize_lang(default)


