#: The only URL schemes this program will ever open. The AI base URL is
#: user-configurable, and urllib happily opens file:// and ftp:// — a pasted
#: or mistyped base URL must not turn into a local-file read.
ALLOWED_URL_SCHEMES = ("http", "https")


class UnsafeUrlError(ValueError):
    """Raised when a URL uses a scheme this program refuses to open."""


def guard_url(url):
    """Return `url` if it is an http(s) URL, else raise UnsafeUrlError.

    Pure and testable; every urlopen call site in this program goes through it.
    """
    from urllib.parse import urlparse
    metin = str(url or "").strip()
    try:
        parca = urlparse(metin)
    except Exception as exc:
        raise UnsafeUrlError("URL cozumlenemedi / unparseable URL") from exc
    if parca.scheme.lower() not in ALLOWED_URL_SCHEMES:
        raise UnsafeUrlError(
            "yalnizca http/https acilir, gelen: %r / only http(s) may be opened"
            % (parca.scheme or "(bos)"))
    if not parca.netloc:
        raise UnsafeUrlError("URL sunucu adi tasimiyor / URL has no host")
    return metin

