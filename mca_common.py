def is_ignored_resource(path):
    name = Path(path).name.lower()
    if name.startswith("."):
        return True
    return any(pat in name for pat in IGNORED_NAME_PATTERNS)


def course_order_keywords():
    """The active ordering: the user's course_order.txt if present, else the default.

    A user's file wins so nobody has to edit the source to make their own
    folder names sort correctly.
    """
    try:
        yol = Path(app_paths.resources_dir()) / COURSE_ORDER_FILE
        if yol.is_file():
            satirlar = [s.strip().lower() for s in
                        yol.read_text(encoding="utf-8").splitlines()]
            gruplar = [(s,) for s in satirlar if s and not s.startswith("#")]
            if gruplar:
                return gruplar
    except Exception:
        pass
    return COURSE_ORDER_KEYWORDS


def course_key(name):
    """Sort key for a course folder: (teaching-order index, lowercased name).

    The MOST SPECIFIC keyword wins, not the first one listed — otherwise
    "Linear Algebra" would be caught by the plain "algebra" group and sort
    before Geometry. Unmatched folders sort last, alphabetically, instead of
    being silently reordered.
    """
    n = name.lower().replace("&", "and")
    en_iyi = None                      # (-keyword_length, index)
    for idx, grup in enumerate(course_order_keywords()):
        for key in grup:
            k = key.replace("&", "and")
            if k in n:
                aday = (-len(k), idx)
                if en_iyi is None or aday < en_iyi:
                    en_iyi = aday
    return (en_iyi[1] if en_iyi else 99, name.lower())


def estimate_tokens(text):
    return max(1, math.ceil(len(text or "") / 4))


def safe_output_tokens(prompt, kind="answer"):
    p = estimate_tokens(prompt)
    if kind == "test":
        return 64
    if kind == "resource":
        return min(900, max(420, 1600 - p // 2))
    return min(1100, max(500, 1800 - p // 2))


class RoundedButton(tk.Canvas):
    """A soft, rounded-corner button drawn on a Canvas (pure Tkinter).

    ttk/clam buttons have hard square corners; this gives the warm, pill-shaped
    look of the "Sıcak Çalışma" design. Supports hover, press, disabled state,
    fill="x" stretching, and .config(text=...) for live language switching.
    """

    def __init__(self, master, text="", command=None, radius=14,
                 bg=None, fg=None, hover=None, parent_bg=None,
                 font=("Segoe UI Semibold", 9), padx=13, pady=7, style=None,
                 takefocus=None, width=None, **kw):
        import tkinter.font as _tkfont
        # Translate ttk-style kwargs so a blanket ttk.Button -> RoundedButton
        # swap works without per-call edits.
        if style == "Calc.TButton":
            # Sabit beyaz degil THEME yuzeyi: koyu temada beyaz tus ustune
            # fildisi metin okunmuyordu (ekran dogrulamasinda yakalandi).
            bg = bg or THEME["surface"]
            font = ("Segoe UI Semibold", 13)
            padx, pady, radius = 10, 12, 12
        elif style == "Accent.TButton":
            bg = bg or THEME["accent"]; fg = fg or "#FFFFFF"; hover = hover or "#EC8A4B"
        elif style == "Save.TButton":
            bg = bg or THEME["green"]; fg = fg or "#FFFFFF"; hover = hover or "#23B768"
        _char_w = None
        if isinstance(width, int):
            _char_w = width  # ttk width is in characters; approximate below
        if parent_bg is None:
            parent_bg = THEME["panel"]
        super().__init__(master, bd=0, highlightthickness=0, bg=parent_bg,
                         takefocus=0, cursor="hand2", **kw)
        self._command = command
        self._radius = radius
        self._bg = bg or THEME["panel2"]
        self._fg = fg or THEME["text"]
        self._hover = hover or THEME["accent_soft"]
        self._font = _tkfont.Font(family=font[0], size=font[1],
                                  weight=("bold" if len(font) > 2 and font[2] == "bold" else "normal"))
        self._padx = padx
        self._pady = pady
        self._text = text
        self._state = "normal"
        self._fill = self._bg
        tw = self._font.measure(text or "")
        if _char_w:
            tw = max(tw, self._font.measure("0") * _char_w)
        th = self._font.metrics("linespace")
        self._req_w = tw + padx * 2
        self._req_h = th + pady * 2
        self.configure(width=self._req_w, height=self._req_h)
        self.bind("<Configure>", lambda e: self._render())
        self.bind("<Enter>", self._on_enter)
        self.bind("<Leave>", self._on_leave)
        self.bind("<ButtonPress-1>", self._on_press)
        self.bind("<ButtonRelease-1>", self._on_release)
        self._render()

    def _round_rect(self, x1, y1, x2, y2, r, **kw):
        r = max(0, min(r, (x2 - x1) // 2, (y2 - y1) // 2))
        pts = [
            x1 + r, y1, x2 - r, y1, x2, y1, x2, y1 + r, x2, y2 - r, x2, y2,
            x2 - r, y2, x1 + r, y2, x1, y2, x1, y2 - r, x1, y1 + r, x1, y1,
        ]
        return self.create_polygon(pts, smooth=True, **kw)

    def _render(self, fill=None):
        if fill is not None:
            self._fill = fill
        self.delete("all")
        w = self.winfo_width() or self._req_w
        h = self.winfo_height() or self._req_h
        if w <= 1:
            w = self._req_w
        if h <= 1:
            h = self._req_h
        self._round_rect(1, 1, w - 1, h - 1, self._radius,
                         fill=self._fill, outline=self._fill)
        fg = self._fg if self._state == "normal" else THEME["muted"]
        self.create_text(w // 2, h // 2, text=self._text, fill=fg, font=self._font)

    def _on_enter(self, _e):
        if self._state == "normal":
            self._render(self._hover)

    def _on_leave(self, _e):
        if self._state == "normal":
            self._render(self._bg)

    def _on_press(self, _e):
        if self._state == "normal":
            self._render(self._bg)

    def _on_release(self, _e):
        if self._state == "normal":
            self._render(self._hover)
            if callable(self._command):
                self._command()

    def configure(self, **kw):
        kw.pop("style", None)
        kw.pop("takefocus", None)
        if "text" in kw:
            self._text = kw.pop("text")
        if "command" in kw:
            self._command = kw.pop("command")
        if "state" in kw:
            self._state = "disabled" if kw.pop("state") in ("disabled", "disable") else "normal"
        if "bg" in kw:
            self._bg = kw.pop("bg")
            self._fill = self._bg
        if kw:
            super().configure(**kw)
        if self.winfo_exists():
            self._render()

    config = configure


