def write_sample_pdf(path: Path) -> None:
    """Render the sample PDF with PyMuPDF, falling back to a plain text file."""
    try:
        import fitz
    except Exception:
        path.with_suffix(".txt").write_text(
            "\n\n".join(t + "\n" + "\n".join(b) for t, b in PAGES), encoding="utf-8")
        print("   [!] PyMuPDF absent - wrote a .txt sample instead of a .pdf")
        return
    doc = fitz.open()
    for title, body in PAGES:
        page = doc.new_page(width=595, height=842)          # A4
        page.insert_text((60, 80), "Math Course AI - Demo Course Notes",
                         fontname="helv", fontsize=16)
        page.insert_text((60, 104), "SYNTHETIC SAMPLE - CC0 - no real course content",
                         fontname="helv", fontsize=9)
        page.insert_text((60, 150), title, fontname="hebo", fontsize=13)
        y = 185
        for line in body:
            page.insert_text((60, y), line, fontname="helv", fontsize=11)
            y += 19
    doc.set_metadata({"title": "Math Course AI - Demo Course Notes (synthetic)",
                      "author": "", "subject": "Synthetic sample content, CC0",
                      "keywords": "", "creator": "make_demo_resources.py",
                      "producer": "PyMuPDF"})
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(path))
    doc.close()
    print("   [OK] %s (%d pages)" % (path.name, len(PAGES)))


def build(target: Path) -> Path:
    target.mkdir(parents=True, exist_ok=True)
    (target / "_README.txt").write_text(
        "Synthetic demo course library for Math Course AI.\n"
        "Generated by tools/make_demo_resources.py. No third-party material,\n"
        "no personal data. Safe to delete and regenerate at any time.\n",
        encoding="utf-8")
    for course, n in COURSES:
        for sub in SUBFOLDERS[:n - 1] or SUBFOLDERS[:1]:
            (target / course / sub).mkdir(parents=True, exist_ok=True)
        notes = target / course / "02 Notes"
        notes.mkdir(parents=True, exist_ok=True)
        (notes / "_placeholder.txt").write_text(
            "Synthetic placeholder for %s.\n" % course, encoding="utf-8")
    write_sample_pdf(target / COURSES[0][0] / "02 Notes" / "Demo Course Notes (CC0).pdf")
    print("   [OK] demo course tree at", target)
    return target


if __name__ == "__main__":
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else (ROOT / "demo_resources")
    build(dest)
