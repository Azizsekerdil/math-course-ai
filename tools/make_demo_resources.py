"""Build the SYNTHETIC demo course library used for screenshots and the deck.

Why this exists
---------------
The presentation screenshots used to be photographs of the maintainer's own
machine. They therefore rendered

  * an absolute development path (``D:\\...\\Resources``), and
  * the folder names of a third party's commercial course catalogue,

neither of which belongs in a public repository. This script generates a
course tree that is obviously synthetic, contains no third-party brand and no
personal data, and produces its own sample PDF so nothing copyrighted is ever
opened during a capture.

Everything it writes is generated here and now. There is no real course
material, no learner data and no network access.

Usage:
    python tools/make_demo_resources.py [target_dir]
Default target: <repo>/demo_resources
"""

