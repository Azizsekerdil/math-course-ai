def builtin_pack_info(pack, lang="tr"):
    return {
        "id": pack["id"],
        "name": pack["name_tr"] if lang == "tr" else pack["name_en"],
        "course": pack["course"],
        "kind": "generator",
        "license": BUILTIN_LICENSE,
        "attribution": BUILTIN_ATTRIBUTION,
        "source_url": "",
        "count": "∞",
        "langs": "tr, en",
    }


def generate(pack_id, count=20, lang="tr", seed=None, difficulty=None):
    """Generate `count` unique questions from a built-in pack.

    Returns a list of dicts: question/answer/topic/difficulty/course/lang/
    source_pack/license. Unlimited + exact answers + no third-party licence.
    """
    pack = next((p for p in BUILTIN_PACKS if p["id"] == pack_id), None)
    if pack is None:
        return []
    rng = random.Random(seed)
    gens = list(pack["generators"])
    out, seen, guard = [], set(), 0
    target = max(1, int(count or 1))
    while len(out) < target and guard < target * 60:
        guard += 1
        q, a, topic, diff = rng.choice(gens)(rng, lang)
        if difficulty and diff != difficulty:
            continue
        if q in seen:
            continue
        seen.add(q)
        out.append({
            "question": q, "answer": a, "topic": topic, "difficulty": diff,
            "course": pack["course"], "lang": lang, "source_pack": pack["id"],
            "license": BUILTIN_LICENSE, "attribution": BUILTIN_ATTRIBUTION,
        })
    return out


