def export_pack(rows, path, name="", course="", lang="tr",
                license_text="", attribution="", source_url="",
                include_images=None):
    """Soru bankasi satirlarini (sqlite3.Row/dict) harici paket JSON'una yazar.

    Cikti, load_external_packs'in okudugu semanin aynisidir: dosya bir
    arkadasin question_packs/ klasorune kopyalandiginda Soru Paketleri
    sekmesinden dogrudan ice aktarilabilir. Lisans bos birakilirsa yukleyici
    paketi UNKNOWN olarak isaretler ve aktarmadan once uyari cikar — kisisel
    paylasim icin bu bilincli bir varsayilandir.

    BICIM (V48): dosya adi `.mcpack` ile bitiyorsa ZIP paketi yazilir
    (paket.json + images/) ve GORSELLI SORULAR DA TASINIR. `.json` ise eski
    duz bicim yazilir ve gorselden ibaret sorular atlanir — eski surumlerle
    ve arkadasin eski klonuyla uyum icin bu yol korunuyor.
    `include_images=True/False` ile bicim elle zorlanabilir.

    Hic yazilacak soru kalmazsa DOSYA OLUSTURULMAZ.
    Doner: (yazilan_sayisi, atlanan_sayisi).
    """
    p_on = Path(path)
    if include_images is None:
        include_images = p_on.suffix.lower() == MCPACK_UZANTI
    def _field(row, key, default=""):
        try:
            v = row[key]
        except (KeyError, IndexError, TypeError):
            return default
        return default if v is None else v

    questions = []
    skipped = 0
    gorseller = {}          # zip ici ad -> disk yolu
    for r in rows or []:
        text = str(_field(r, "question_text") or _field(r, "question") or "").strip()
        gorsel_yol = str(_field(r, "image_path") or "").strip()
        gorsel_var = bool(gorsel_yol) and Path(gorsel_yol).exists()
        if is_image_only(text) and not (include_images and gorsel_var):
            # Duz .json bicimi gorsel tasiyamaz; gorseli olmayan (ya da
            # dosyasi kayip) bir "gorsel soru" her iki bicimde de atlanir.
            skipped += 1
            continue
        entry = {
            "question": text,
            "answer": str(_field(r, "answer_text") or _field(r, "answer") or ""),
            "topic": str(_field(r, "topic") or ""),
            "difficulty": str(_field(r, "difficulty") or "Medium"),
        }
        # Satirin kendi ders/dil bilgisi tasinir; bos ise yukleyici paket
        # duzeyindeki degerlere duser (karisik bankalarda 'en' soru 'tr'
        # damgalanmasin, ders bilgisi silinmesin).
        row_course = str(_field(r, "course") or "").strip()
        if row_course:
            entry["course"] = row_course
        row_lang = str(_field(r, "lang") or "").strip()
        if row_lang:
            entry["lang"] = row_lang
        choices = _field(r, "choices", None)
        if isinstance(choices, str) and choices.strip():
            try:
                choices = json.loads(choices)
            except Exception:
                choices = None
        if isinstance(choices, list) and choices:
            entry["choices"] = [str(c) for c in choices]
            cc = str(_field(r, "correct_choice") or "").strip().upper()
            if cc:
                entry["correct_choice"] = cc
        if include_images and gorsel_var:
            # Zip icindeki ad benzersiz olmali: ayni dosya adi iki farkli
            # kaynaktan gelebilir, ustune yazmak sessiz veri kaybi olurdu.
            kaynak = Path(gorsel_yol)
            ad = kaynak.name
            sayac = 1
            while ad in gorseller and gorseller[ad] != str(kaynak):
                ad = f"{kaynak.stem}_{sayac}{kaynak.suffix}"
                sayac += 1
            gorseller[ad] = str(kaynak)
            entry["image"] = f"{MCPACK_IMAGES}/{ad}"
        questions.append(entry)

    if not questions:
        return 0, skipped

