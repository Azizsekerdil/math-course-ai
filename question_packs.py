def import_into_store(store, pack_id, count=20, lang="tr", difficulty=None,
                      seed=None, folder=None):
    """Add pack questions to a StudentStore question bank. Skips duplicates by
    (question_text). Returns the number actually added."""
    rows = get_questions(pack_id, count=count, lang=lang, difficulty=difficulty,
                         seed=seed, folder=folder)
    if not rows:
        return 0
    existing = {(r["question_text"] or "").strip() for r in store.list_questions(limit=100000)}
    added = 0
    for r in rows:
        if r["question"].strip() in existing:
            continue
        qid = store.add_question(
            r["question"], r["answer"], course=r["course"], topic=r["topic"],
            difficulty=r["difficulty"], tags=r["source_pack"],
            source_pack=r["source_pack"], license_text=r["license"], lang=r["lang"],
            image_path=_gorseli_yerlestir(r),
            choices=r.get("choices"), correct_choice=r.get("correct_choice", ""))
        if qid:
            added += 1
            existing.add(r["question"].strip())
    return added


# --- .mcpack extraction limits -------------------------------------------
# A pack is untrusted user-supplied input. Zip-slip was already defended by
# _guvenli_gorsel_adi(); these caps close the remaining resource exhaustion
# (zip bomb) hole: an entry that declares 12 KB can still expand to gigabytes,
# and shutil.copyfileobj would happily write all of it.
MCPACK_MAX_IMAGE_BYTES = 8 * 1024 * 1024          # 8 MiB per extracted image
MCPACK_MAX_MEMBERS = 2000                          # members in one archive
MCPACK_MAX_TOTAL_BYTES = 256 * 1024 * 1024         # 256 MiB declared, whole pack
MCPACK_MAX_RATIO = 200                             # uncompressed / compressed


def mcpack_arsiv_guvenli_mi(zf, max_members=MCPACK_MAX_MEMBERS,
                            max_total=MCPACK_MAX_TOTAL_BYTES,
                            max_ratio=MCPACK_MAX_RATIO):
    """(ok, sebep) — archive-level sanity check BEFORE anything is extracted.

    Pure and testable: takes any object exposing `infolist()`.
    """
    bilgiler = list(zf.infolist())
    if len(bilgiler) > max_members:
        return False, ("uye sayisi cok yuksek / too many members: %d > %d"
                       % (len(bilgiler), max_members))
    toplam = sum(int(getattr(i, "file_size", 0) or 0) for i in bilgiler)
    if toplam > max_total:
        return False, ("acilmis boyut cok buyuk / declared size too large: %d > %d"
                       % (toplam, max_total))
    sikistirilmis = sum(int(getattr(i, "compress_size", 0) or 0) for i in bilgiler)
    if sikistirilmis > 0 and (toplam / sikistirilmis) > max_ratio:
        return False, ("sikistirma orani supheli / suspicious compression ratio: %.1fx > %dx"
                       % (toplam / sikistirilmis, max_ratio))
    return True, ""


def _sinirli_kopyala(kaynak, cikti, limit=MCPACK_MAX_IMAGE_BYTES, blok=64 * 1024):
    """copyfileobj with a hard byte ceiling. Raises ValueError past the limit."""
    yazilan = 0
    while True:
        parca = kaynak.read(blok)
        if not parca:
            return yazilan
        yazilan += len(parca)
        if yazilan > limit:
            raise ValueError("gorsel sinirin ustunde / image exceeds %d bytes" % limit)
        cikti.write(parca)


def _gorseli_yerlestir(entry):
    """.mcpack icindeki gorseli question_images klasorune cikarir → yol ya da "".

    Ayni adli bir dosya zaten varsa UZERINE YAZILMAZ; ad numaralanir. Hata
    yutulur: gorsel cikarilamasa da sorunun kendisi bankaya girsin.
    """
    rel = entry.get("image_in_pack")
    zip_yolu = entry.get("_zip")
    if not rel or not zip_yolu:
        return ""
    ad = _guvenli_gorsel_adi(rel)
    if not ad:
        return ""
    try:
        hedef_klasor = _gorsel_hedef_klasoru()
        hedef = hedef_klasor / ad
        sayac = 1
        while hedef.exists():
            hedef = hedef_klasor / f"{Path(ad).stem}_{sayac}{Path(ad).suffix}"
            sayac += 1
        with zipfile.ZipFile(zip_yolu) as z:
            ok, _sebep = mcpack_arsiv_guvenli_mi(z)
            if not ok:
                return ""
            bilgi = z.getinfo(rel)
            if int(getattr(bilgi, "file_size", 0) or 0) > MCPACK_MAX_IMAGE_BYTES:
                return ""
            try:
                with z.open(rel) as kaynak, open(hedef, "wb") as cikti:
                    _sinirli_kopyala(kaynak, cikti)
            except ValueError:
                # Beyan edilen boyut yalan soylemis olabilir: yarim dosyayi birakma.
                try:
                    hedef.unlink()
                except Exception:
                    pass
                return ""
        return str(hedef)
    except Exception:
        return ""
