def gen_arithmetic(rng, lang):
    a, b = rng.randint(2, 99), rng.randint(2, 99)
    op = rng.choice(["+", "-", "*"])
    val = {"+": a + b, "-": a - b, "*": a * b}[op]
    return (f"{a} {op} {b} = ?", str(val),
            _t(lang, "Dört İşlem", "Arithmetic"), "Easy")


def gen_order_of_operations(rng, lang):
    a, b, c, d = (rng.randint(2, 12) for _ in range(4))
    q = f"{a} + {b} × {c} − {d} = ?"
    return (q, str(a + b * c - d), _t(lang, "İşlem Önceliği", "Order of Operations"), "Easy")


def gen_integers(rng, lang):
    a, b = rng.randint(-40, -2), rng.randint(2, 40)
    op = rng.choice(["+", "-", "*"])
    val = {"+": a + b, "-": a - b, "*": a * b}[op]
    return (f"({a}) {op} ({b}) = ?", str(val), _t(lang, "Tam Sayılar", "Integers"), "Easy")


def gen_fractions(rng, lang):
    a, b, c, d = rng.randint(1, 9), rng.randint(2, 9), rng.randint(1, 9), rng.randint(2, 9)
    op = rng.choice(["+", "-", "*"])
    f1, f2 = Fraction(a, b), Fraction(c, d)
    val = {"+": f1 + f2, "-": f1 - f2, "*": f1 * f2}[op]
    return (f"{a}/{b} {op} {c}/{d} = ?  " + _t(lang, "(sadeleştir)", "(simplify)"),
            _frac_str(val), _t(lang, "Kesirler", "Fractions"), "Medium")


def gen_percentage(rng, lang):
    p, n = rng.choice([5, 10, 12, 15, 20, 25, 40, 50]), rng.randint(2, 40) * 10
    val = Fraction(p, 100) * n
    return (_t(lang, f"{n} sayısının %{p} kaçtır?", f"What is {p}% of {n}?"),
            _frac_str(val), _t(lang, "Yüzde", "Percentage"), "Easy")


def gen_linear_equation(rng, lang):
    a = rng.randint(2, 12)
    x = rng.randint(-9, 9)
    b = rng.randint(-20, 20)
    c = a * x + b
    sign = "+" if b >= 0 else "−"
    q = _t(lang, f"{a}x {sign} {abs(b)} = {c} denkleminde x kaçtır?",
           f"Solve for x:  {a}x {sign} {abs(b)} = {c}")
    return (q, f"x = {x}", _t(lang, "Birinci Derece Denklem", "Linear Equations"), "Medium")


def gen_quadratic(rng, lang):
    r1, r2 = rng.randint(-8, 8), rng.randint(-8, 8)
    b, c = -(r1 + r2), r1 * r2
    bs = f"+ {b}x" if b > 0 else (f"− {abs(b)}x" if b < 0 else "")
    cs = f"+ {c}" if c > 0 else (f"− {abs(c)}" if c < 0 else "")
    q = _t(lang, f"x² {bs} {cs} = 0 denkleminin kökleri nedir?",
           f"Find the roots:  x² {bs} {cs} = 0")
    roots = sorted({r1, r2})
    return (q, "x = " + ", ".join(str(r) for r in roots),
            _t(lang, "İkinci Derece Denklem", "Quadratic Equations"), "Hard")


def gen_system2(rng, lang):
    x, y = rng.randint(-6, 6), rng.randint(-6, 6)
    a1, b1, a2, b2 = (rng.randint(1, 6) for _ in range(4))
    if a1 * b2 - a2 * b1 == 0:
        b2 += 1
    c1, c2 = a1 * x + b1 * y, a2 * x + b2 * y
    q = _t(lang, f"Sistemi çöz:  {a1}x + {b1}y = {c1}   ve   {a2}x + {b2}y = {c2}",
           f"Solve the system:  {a1}x + {b1}y = {c1}   and   {a2}x + {b2}y = {c2}")
    return (q, f"x = {x}, y = {y}", _t(lang, "Denklem Sistemi", "Systems of Equations"), "Hard")


def gen_exponent(rng, lang):
    a, m, n = rng.randint(2, 6), rng.randint(2, 5), rng.randint(2, 5)
    q = _t(lang, f"{a}^{m} × {a}^{n} = ?  (tek üs olarak sadeleştir ve değeri yaz)",
           f"Simplify and evaluate:  {a}^{m} × {a}^{n} = ?")
    return (q, f"{a}^{m + n} = {a ** (m + n)}", _t(lang, "Üslü Sayılar", "Exponents"), "Medium")


def gen_slope(rng, lang):
    x1, y1 = rng.randint(-8, 8), rng.randint(-8, 8)
    x2, y2 = rng.randint(-8, 8), rng.randint(-8, 8)
    if x1 == x2:
        x2 += 1
    m = Fraction(y2 - y1, x2 - x1)
    q = _t(lang, f"A({x1}, {y1}) ve B({x2}, {y2}) noktalarından geçen doğrunun eğimi nedir?",
           f"Find the slope of the line through A({x1}, {y1}) and B({x2}, {y2}).")
    return (q, f"m = {_frac_str(m)}", _t(lang, "Eğim", "Slope"), "Medium")


def gen_rect_area(rng, lang):
    a, b = rng.randint(3, 25), rng.randint(3, 25)
    if rng.random() < 0.5:
        q = _t(lang, f"Kenarları {a} ve {b} olan dikdörtgenin alanı kaçtır?",
               f"Find the area of a rectangle with sides {a} and {b}.")
        return (q, str(a * b), _t(lang, "Alan", "Area"), "Easy")
    q = _t(lang, f"Kenarları {a} ve {b} olan dikdörtgenin çevresi kaçtır?",
           f"Find the perimeter of a rectangle with sides {a} and {b}.")
    return (q, str(2 * (a + b)), _t(lang, "Çevre", "Perimeter"), "Easy")


def gen_pythagoras(rng, lang):
    k = rng.randint(1, 6)
    a, b, c = rng.choice([(3, 4, 5), (5, 12, 13), (8, 15, 17), (7, 24, 25)])
    a, b, c = a * k, b * k, c * k
    q = _t(lang, f"Dik kenarları {a} ve {b} olan dik üçgenin hipotenüsü kaçtır?",
           f"A right triangle has legs {a} and {b}. Find the hypotenuse.")
    return (q, str(c), _t(lang, "Pisagor", "Pythagorean Theorem"), "Medium")


def gen_circle(rng, lang):
    r = rng.randint(2, 15)
    if rng.random() < 0.5:
        q = _t(lang, f"Yarıçapı {r} olan çemberin alanı nedir? (π cinsinden)",
               f"Find the area of a circle with radius {r}. (in terms of π)")
        return (q, f"{r * r}π", _t(lang, "Çember", "Circles"), "Medium")
    q = _t(lang, f"Yarıçapı {r} olan çemberin çevresi nedir? (π cinsinden)",
           f"Find the circumference of a circle with radius {r}. (in terms of π)")
    return (q, f"{2 * r}π", _t(lang, "Çember", "Circles"), "Medium")


def gen_matrix_det2(rng, lang):
    a, b, c, d = (rng.randint(-9, 9) for _ in range(4))
    q = _t(lang, f"[[{a}, {b}], [{c}, {d}]] matrisinin determinantı nedir?",
           f"Find the determinant of [[{a}, {b}], [{c}, {d}]].")
    return (q, str(a * d - b * c), _t(lang, "Determinant", "Determinants"), "Medium")


def gen_matrix_add(rng, lang):
    m1 = [[rng.randint(-9, 9) for _ in range(2)] for _ in range(2)]
    m2 = [[rng.randint(-9, 9) for _ in range(2)] for _ in range(2)]
    s = [[m1[i][j] + m2[i][j] for j in range(2)] for i in range(2)]
    q = _t(lang, f"{m1} + {m2} = ?  (matris toplamı)", f"Compute the matrix sum: {m1} + {m2}")
    return (q, str(s), _t(lang, "Matris Toplama", "Matrix Addition"), "Easy")


def gen_dot_product(rng, lang):
    u = [rng.randint(-9, 9) for _ in range(3)]
    v = [rng.randint(-9, 9) for _ in range(3)]
    q = _t(lang, f"u = {u} ve v = {v} vektörlerinin skaler (nokta) çarpımı nedir?",
           f"Find the dot product of u = {u} and v = {v}.")
    return (q, str(sum(a * b for a, b in zip(u, v))),
            _t(lang, "Nokta Çarpım", "Dot Product"), "Medium")


def gen_derivative_poly(rng, lang):
    a, n, b = rng.randint(2, 9), rng.randint(2, 5), rng.randint(1, 9)
    q = _t(lang, f"f(x) = {a}x^{n} + {b}x  fonksiyonunun türevi nedir?",
           f"Find the derivative of f(x) = {a}x^{n} + {b}x.")
    ns = f"{a * n}x^{n - 1}" if n - 1 > 1 else f"{a * n}x"
    return (q, f"f'(x) = {ns} + {b}", _t(lang, "Türev", "Derivatives"), "Medium")


