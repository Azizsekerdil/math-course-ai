def _external_pack_path(folder=None):
    return Path(folder) if folder else PACKS_DIR


def load_external_packs(folder=None):
    """Read openly-licensed packs from `question_packs/*.json`.

    Required keys: id, name, questions[]. Recommended: course, lang, license,
    attribution, source_url. A pack with no `license` is flagged 'UNKNOWN' so the
    user is warned before importing it.
    """
    base = _external_pack_path(folder)
    packs = []
    try:
        if not base.exists():
            return packs
        dosyalar = sorted(base.glob("*.json")) + sorted(base.glob("*" + MCPACK_UZANTI))
        for p in dosyalar:
            zip_yolu = ""
            try:
                if p.suffix.lower() == MCPACK_UZANTI:
                    with zipfile.ZipFile(p) as z:
                        ok, _sebep = mcpack_arsiv_guvenli_mi(z)
                        if not ok:
                            continue      # zip bomb / asiri paket: sessizce atla
                        bilgi = z.getinfo(MCPACK_JSON)
                        if int(getattr(bilgi, "file_size", 0) or 0) > MCPACK_MAX_TOTAL_BYTES:
                            continue
                        data = json.loads(z.read(MCPACK_JSON).decode("utf-8"))
                    zip_yolu = str(p)
                else:
                    data = json.loads(p.read_text(encoding="utf-8"))
            except Exception:
                continue        # bozuk/yarim paket listeyi cokertmez
            qs = data.get("questions")
            if not isinstance(qs, list) or not qs:
                continue
            packs.append({
                "_zip": zip_yolu,
                "kind_detail": "mcpack" if zip_yolu else "json",
                "images": int(data.get("images") or 0),
                "id": str(data.get("id") or p.stem),
                "name": str(data.get("name") or p.stem),
                "course": str(data.get("course") or ""),
                "kind": "external",
                "license": str(data.get("license") or "UNKNOWN — check before use"),
                "attribution": str(data.get("attribution") or ""),
                "source_url": str(data.get("source_url") or ""),
                "count": len(qs),
                "langs": str(data.get("lang") or "?"),
                "_path": str(p),
                "_questions": qs,
            })
    except Exception:
        pass
    return packs


def external_questions(pack, count=None, difficulty=None):
    out = []
    for q in pack.get("_questions", []):
        if not isinstance(q, dict):
            continue
        text = str(q.get("question") or q.get("question_text") or "").strip()
        if not text:
            continue
        diff = str(q.get("difficulty") or "Medium")
        if difficulty and diff != difficulty:
            continue
        entry = {
            "question": text,
            "answer": str(q.get("answer") or q.get("answer_text") or ""),
            "topic": str(q.get("topic") or ""),
            "difficulty": diff,
            "course": str(q.get("course") or pack.get("course") or ""),
            "lang": str(q.get("lang") or pack.get("langs") or ""),
            "source_pack": pack["id"],
            "license": pack.get("license", ""),
            "attribution": pack.get("attribution", ""),
        }
        # Sikli sorular (A-E) paketten geldiginde siklarini kaybetmesin:
        # export_pack bu alanlari yazar, eski paketlerde yoklar ve atlanir.
        ch = q.get("choices")
        if isinstance(ch, list) and ch:
            entry["choices"] = [str(c) for c in ch]
            cc = str(q.get("correct_choice") or "").strip().upper()
            if cc:
                entry["correct_choice"] = cc
        # .mcpack: gorsel HENUZ cikarilmaz — yalniz nerede oldugu tasinir.
        # Cikarma ice aktarma aninda olur (onizleme diske dosya birakmasin).
        gorsel = _guvenli_gorsel_adi(q.get("image"))
        if gorsel and pack.get("_zip"):
            entry["image_in_pack"] = f"{MCPACK_IMAGES}/{gorsel}"
            entry["_zip"] = pack["_zip"]
        out.append(entry)
        if count and len(out) >= int(count):
            break
    return out


def list_packs(lang="tr", folder=None):
    """Built-in generator packs + any external JSON packs, for the picker."""
    return [builtin_pack_info(p, lang) for p in BUILTIN_PACKS] + load_external_packs(folder)


def get_questions(pack_id, count=20, lang="tr", difficulty=None, seed=None, folder=None):
    """Uniform accessor used by the UI: works for built-in and external packs."""
    if any(p["id"] == pack_id for p in BUILTIN_PACKS):
        return generate(pack_id, count=count, lang=lang, seed=seed, difficulty=difficulty)
    for p in load_external_packs(folder):
        if p["id"] == pack_id:
            return external_questions(p, count=count, difficulty=difficulty)
    return []


IMAGE_ONLY_PREFIX = "[Görsel soru]"


def is_image_only(text):
    """Kirpilmis-gorsel placeholder metnini tanir (paketlere yazilamaz).

    Hem export_pack hem UI ayni kurali kullansin diye tek yerde."""
    t = str(text or "").strip()
