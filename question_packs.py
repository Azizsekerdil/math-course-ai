def _guvenli_gorsel_adi(rel):
    """ZIP icindeki gorsel yolunu dogrular → dosya adi ya da None.

    Kabul: 'images/xyz.png'. Red: mutlak yol, '..', alt klasor, tanimadigi
    uzanti. Kotu niyetli ya da bozuk bir paket disari yazamasin diye.
    """
    rel = str(rel or "").replace("\\", "/").strip()
    if not rel or not rel.startswith(MCPACK_IMAGES + "/"):
        return None
    ad = rel[len(MCPACK_IMAGES) + 1:]
    if not ad or "/" in ad or ad in (".", "..") or ad.startswith("."):
        return None
    if Path(ad).suffix.lower() not in _GECERLI_GORSEL_UZANTI:
        return None
    return ad


